import { describe, expect, it } from "vitest";

import { expliquerErreurHttp } from "@/lib/errorMessages";

// expliquerErreurHttp returns translation KEYS (namespace "Errors"), never
// resolved text: the components call t(key) themselves (see ChatView.tsx).
// This module stays usable from both the client and the server, without
// depending on a next-intl context.
describe("expliquerErreurHttp", () => {
  it.each([401, 403])("401/403 -> authTitle, type 'erreur'", (status) => {
    const resultat = expliquerErreurHttp(status);
    expect(resultat.type).toBe("erreur");
    expect(resultat.titreKey).toBe("authTitle");
  });

  it("422 -> validationTitle, type 'erreur', description overridden by the backend", () => {
    const resultat = expliquerErreurHttp(422, "top_k must be positive");
    expect(resultat.type).toBe("erreur");
    expect(resultat.titreKey).toBe("validationTitle");
    expect(resultat.descriptionOverride).toBe("top_k must be positive");
  });

  it("503 -> unavailableTitle, type 'indisponible'", () => {
    const resultat = expliquerErreurHttp(503);
    expect(resultat.type).toBe("indisponible");
    expect(resultat.titreKey).toBe("unavailableTitle");
  });

  it("504 -> timeoutTitle, type 'indisponible'", () => {
    const resultat = expliquerErreurHttp(504);
    expect(resultat.type).toBe("indisponible");
    expect(resultat.titreKey).toBe("timeoutTitle");
    expect(resultat.descriptionKey).toBe("timeoutDescription");
  });

  it("unknown code -> unknownTitle with the code as an interpolation value, type 'erreur'", () => {
    const resultat = expliquerErreurHttp(418, "I'm a teapot");
    expect(resultat.type).toBe("erreur");
    expect(resultat.titreKey).toBe("unknownTitle");
    expect(resultat.titreValues).toEqual({ status: 418 });
    expect(resultat.descriptionOverride).toBe("I'm a teapot");
  });

  // Errors generated by OUR OWN proxy (code present): always a translation
  // key, NEVER the raw "message" (internal/log-only) — this is what lets
  // the active language (fr/en/de) be respected.
  it("code='empty_question' -> validationDefault, no descriptionOverride (message ignored)", () => {
    const resultat = expliquerErreurHttp(400, "The question is empty.", "empty_question");
    expect(resultat.titreKey).toBe("validationTitle");
    expect(resultat.descriptionKey).toBe("validationDefault");
    expect(resultat.descriptionOverride).toBeUndefined();
  });

  it("code='invalid_json' -> validationDefault", () => {
    const resultat = expliquerErreurHttp(400, "Invalid JSON request body.", "invalid_json");
    expect(resultat.descriptionKey).toBe("validationDefault");
    expect(resultat.descriptionOverride).toBeUndefined();
  });

  it("code='question_too_long' -> questionTooLong with values.max passed through", () => {
    const resultat = expliquerErreurHttp(400, "Question too long (max 2000 characters).", "question_too_long", {
      max: 2000,
    });
    expect(resultat.descriptionKey).toBe("questionTooLong");
    expect(resultat.descriptionValues).toEqual({ max: 2000 });
    expect(resultat.descriptionOverride).toBeUndefined();
  });

  it("code='api_key_missing' -> serverMisconfigured, title with status=500", () => {
    const resultat = expliquerErreurHttp(500, "BACKEND_API_KEY is not configured.", "api_key_missing");
    expect(resultat.titreKey).toBe("unknownTitle");
    expect(resultat.titreValues).toEqual({ status: 500 });
    expect(resultat.descriptionKey).toBe("serverMisconfigured");
  });

  it("code='backend_error_status' -> unknownDefault with the status passed through", () => {
    const resultat = expliquerErreurHttp(502, "The backend responded 502.", "backend_error_status", { status: 502 });
    expect(resultat.titreValues).toEqual({ status: 502 });
    expect(resultat.descriptionKey).toBe("unknownDefault");
  });

  it("code='timeout_no_response' -> timeoutTitle/timeoutDescription (reuses the existing keys)", () => {
    const resultat = expliquerErreurHttp(504, "The backend did not respond in time.", "timeout_no_response");
    expect(resultat.titreKey).toBe("timeoutTitle");
    expect(resultat.descriptionKey).toBe("timeoutDescription");
    expect(resultat.type).toBe("indisponible");
  });

  it("code='backend_unreachable' -> unavailableTitle/unavailableDefault (reuses the existing keys)", () => {
    const resultat = expliquerErreurHttp(503, "Could not reach the backend.", "backend_unreachable");
    expect(resultat.titreKey).toBe("unavailableTitle");
    expect(resultat.descriptionKey).toBe("unavailableDefault");
    expect(resultat.type).toBe("indisponible");
  });
});
