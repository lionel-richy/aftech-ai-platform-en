// Simple explanations for every error the Next.js proxy can return.
// "type" determines which visual state component to use on the UI side (see
// components/ui/StateViews.tsx). The actual text lives in
// messages/{locale}.json (namespace "Errors"); this module only returns
// keys, so it can be used from both the client and the server.
import type { ApiErrorCode } from "./types";

type CleTitre = "authTitle" | "validationTitle" | "unavailableTitle" | "timeoutTitle" | "unknownTitle";
type CleDescription =
  | "authDescription"
  | "validationDefault"
  | "questionTooLong"
  | "serverMisconfigured"
  | "unavailableDefault"
  | "timeoutDescription"
  | "unknownDefault";

export interface ErreurExplicationCles {
  titreKey: CleTitre;
  titreValues?: Record<string, number>;
  descriptionKey: CleDescription;
  descriptionValues?: Record<string, number>;
  // Already-resolved text, displayed AS-IS instead of descriptionKey —
  // reserved for the REAL backend's "detail" (untranslated passthrough,
  // like a citation). Never set when the error comes from our own proxy
  // (see CODE_VERS_EXPLICATION below): in that case, descriptionKey always
  // drives the display, in the active language.
  descriptionOverride?: string;
  type: "indisponible" | "erreur";
}

// Errors generated by OUR OWN proxy (see lib/backend.ts and
// app/api/ask/route.ts): always translated via a key, never via the raw
// "message" field (which stays internal/log-only).
const CODE_VERS_EXPLICATION: Record<
  ApiErrorCode,
  (values?: Record<string, number>) => ErreurExplicationCles
> = {
  invalid_json: () => ({ titreKey: "validationTitle", descriptionKey: "validationDefault", type: "erreur" }),
  empty_question: () => ({ titreKey: "validationTitle", descriptionKey: "validationDefault", type: "erreur" }),
  question_too_long: (values) => ({
    titreKey: "validationTitle",
    descriptionKey: "questionTooLong",
    descriptionValues: values,
    type: "erreur",
  }),
  api_key_missing: () => ({
    titreKey: "unknownTitle",
    titreValues: { status: 500 },
    descriptionKey: "serverMisconfigured",
    type: "erreur",
  }),
  backend_error_status: (values) => ({
    titreKey: "unknownTitle",
    titreValues: values,
    descriptionKey: "unknownDefault",
    type: "erreur",
  }),
  timeout_no_response: () => ({ titreKey: "timeoutTitle", descriptionKey: "timeoutDescription", type: "indisponible" }),
  backend_unreachable: () => ({ titreKey: "unavailableTitle", descriptionKey: "unavailableDefault", type: "indisponible" }),
  no_file: () => ({ titreKey: "validationTitle", descriptionKey: "validationDefault", type: "erreur" }),
};

export function expliquerErreurHttp(
  status: number,
  messageBrut?: string,
  code?: ApiErrorCode,
  values?: Record<string, number>,
): ErreurExplicationCles {
  if (code) {
    return CODE_VERS_EXPLICATION[code](values);
  }

  // No code: the error comes from the REAL backend (e.g. a Pydantic
  // "detail" on a 422 for an invalid response_language). messageBrut is then
  // displayed as-is, without translation — exactly like a citation.
  switch (status) {
    case 401:
    case 403:
      return { titreKey: "authTitle", descriptionKey: "authDescription", type: "erreur" };
    case 422:
      return {
        titreKey: "validationTitle",
        descriptionKey: "validationDefault",
        descriptionOverride: messageBrut,
        type: "erreur",
      };
    case 503:
      return {
        titreKey: "unavailableTitle",
        descriptionKey: "unavailableDefault",
        descriptionOverride: messageBrut,
        type: "indisponible",
      };
    case 504:
      return { titreKey: "timeoutTitle", descriptionKey: "timeoutDescription", type: "indisponible" };
    default:
      return {
        titreKey: "unknownTitle",
        titreValues: { status },
        descriptionKey: "unknownDefault",
        descriptionOverride: messageBrut,
        type: "erreur",
      };
  }
}

// Short explanation of an /ask response's status, shown under the badge.
export const EXPLICATION_STATUT_KEYS: Record<
  "COMPLETE" | "PARTIAL" | "NOT_FOUND",
  "explicationComplete" | "explicationPartial" | "explicationNotFound"
> = {
  COMPLETE: "explicationComplete",
  PARTIAL: "explicationPartial",
  NOT_FOUND: "explicationNotFound",
};
