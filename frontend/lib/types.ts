// Types aligned EXACTLY with backend/app/schemas.py — a single source of
// truth on the backend side, this file only mirrors it on the frontend.

export type AnswerStatus = "COMPLETE" | "PARTIAL" | "NOT_FOUND";

// Must stay identical to i18n/config.ts (Locale) and to
// backend/app/schemas.py (AskRequest.response_language).
export type ResponseLanguage = "fr" | "en" | "de";

export interface AskRequest {
  question: string;
  top_k?: number;
  response_language?: ResponseLanguage;
}

export interface SourceItem {
  fichier: string;
  page: number;
  extrait: string;
  score: number;
}

export interface ValidatedClaim {
  affirmation: string;
  fichier: string | null;
  page: number | null;
  citation: string;
  citation_presente: boolean;
  preuve_supported: boolean;
}

export interface Timings {
  recherche_secondes: number;
  generation_secondes: number;
  total_secondes: number;
}

export interface AskResponse {
  answer: string;
  status: AnswerStatus;
  sources: SourceItem[];
  validated_claims: ValidatedClaim[];
  timings: Timings;
  request_id: string;
}

export interface HealthResponse {
  status: "ok" | "degraded";
  version: string;
  ready: boolean;
  llm_model: string;
  embedding_model: string;
  gpu: string;
  // null if no GPU (degraded mode): never a 0 that would suggest a real measurement.
  vram_totale_octets: number | null;
  vram_utilisee_octets: number | null;
  documents_count: number;
  chunks_count: number;
}

export type DocumentStatus = "UPLOADED" | "EXTRACTING" | "INDEXING" | "READY" | "FAILED" | "DELETING";

export interface DocumentItem {
  nom_fichier: string;
  pages: number;
  passages: number;
  hash_sha256: string;
  modele_embeddings: string;
  date_index: string;
  // Absent for "historical" documents (already indexed before dynamic
  // upload existed, never deletable — see backend/app/document_manager.py).
  id?: string;
  statut?: DocumentStatus;
  message_erreur?: string | null;
  taille_octets?: number;
  supprimable: boolean;
}

export interface DocumentUploadResponse {
  id: string;
  nom_original: string;
  statut: DocumentStatus;
}

export interface DocumentStatusResponse {
  id: string;
  nom_original: string;
  statut: DocumentStatus;
  message_erreur: string | null;
  nb_pages: number;
  nb_passages: number;
  date_ajout: string;
}

export interface MetricsResponse {
  uptime_secondes: number;
  requests_total: number;
  status_complete: number;
  status_partial: number;
  status_not_found: number;
  errors_total: number;
  latence_moyenne_secondes: number | null;
}

// Stable code identifying an error generated by OUR OWN proxy (never the
// "detail" text returned by the real backend, which stays an untranslated
// passthrough — like a citation). Lets the client pick the right
// translation (messages/{locale}.json, namespace "Errors") instead of
// displaying the "message" field (internal/log-only) as-is.
export type ApiErrorCode =
  | "invalid_json"
  | "empty_question"
  | "question_too_long"
  | "api_key_missing"
  | "backend_error_status"
  | "timeout_no_response"
  | "backend_unreachable"
  | "no_file";

// Result of a Next.js server-side proxy call: either the data, or a typed
// error (never a silent throw on the component side). "message" stays
// internal (log/debug only); "code"/"values", when present, drive the
// translated display on the client side (see lib/errorMessages.ts).
export type BackendResult<T> =
  | { ok: true; data: T }
  | { ok: false; status: number; message: string; code?: ApiErrorCode; values?: Record<string, number> };
